begin;

create table public.quero_surprise_boxes (
  id integer generated by default as identity primary key,
  name text not null check (length(trim(name)) between 1 and 100),
  description text not null default '' check (length(description) <= 500),
  price integer not null check (price between 1 and 1000000),
  category_id text references public.quero_categories(id) on update cascade on delete set null,
  min_price integer,
  max_price integer,
  is_active boolean not null default true,
  check (
    (min_price is null and max_price is null)
    or (min_price between 1 and 1000000 and max_price between min_price and 1000000)
  )
);

alter table public.quero_surprise_boxes enable row level security;
revoke all on public.quero_surprise_boxes from public, anon, authenticated;

create or replace function public.quero_public_catalog()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $function$
  select jsonb_build_object(
    'categories', coalesce((
      select jsonb_agg(name order by name)
      from public.quero_categories where is_active
    ), '[]'::jsonb),
    'products', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', p.id, 'name', p.name, 'category', c.name,
        'price', coalesce(p.offer_price, p.price),
        'original_price', case when p.offer_price is not null then p.price else null end,
        'emoji', p.emoji, 'color', p.color, 'tag', p.tag, 'description', p.description,
        'is_active', p.is_active
      ) order by p.id)
      from public.quero_products p
      join public.quero_categories c on c.id = p.category_id
      where c.is_active or exists (
        select 1 from public.quero_user_state s
        where p.id = any(s.owned_product_ids)
      )
    ), '[]'::jsonb),
    'surprise_boxes', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', b.id, 'name', b.name, 'description', b.description, 'price', b.price,
        'category_id', b.category_id, 'category', c.name,
        'min_price', b.min_price, 'max_price', b.max_price,
        'eligible_count', (
          select count(*)::integer
          from public.quero_products p
          join public.quero_categories pc on pc.id = p.category_id and pc.is_active
          where p.is_active
            and (b.category_id is null or p.category_id = b.category_id)
            and (b.min_price is null or coalesce(p.offer_price, p.price) >= b.min_price)
            and (b.max_price is null or coalesce(p.offer_price, p.price) <= b.max_price)
        )
      ) order by b.id)
      from public.quero_surprise_boxes b
      left join public.quero_categories c on c.id = b.category_id
      where b.is_active
    ), '[]'::jsonb),
    'missions', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', id, 'icon', icon, 'title', title, 'detail', detail,
        'reward', reward, 'requirement', requirement, 'recurrence', recurrence
      ) order by title)
      from public.quero_missions where is_active
    ), '[]'::jsonb),
    'settings', jsonb_build_object(
      'collection_reward', (select value from public.quero_admin_settings where key = 'collection_reward'),
      'demo_reward', (select value from public.quero_admin_settings where key = 'demo_reward'),
      'demo_cooldown_minutes', (select value from public.quero_admin_settings where key = 'demo_cooldown_minutes')
    )
  );
$function$;

create or replace function public.quero_admin_get_data()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_is_admin boolean;
begin
  if not public.quero_is_staff() then
    raise exception 'Administrator access required';
  end if;
  v_is_admin := public.quero_is_admin();

  return jsonb_build_object(
    'is_admin', v_is_admin,
    'categories', coalesce((
      select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'is_active', is_active) order by name)
      from public.quero_categories
    ), '[]'::jsonb),
    'products', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', p.id, 'name', p.name, 'category_id', p.category_id, 'category', c.name,
        'price', p.price, 'offer_price', p.offer_price,
        'emoji', p.emoji, 'color', p.color, 'tag', p.tag,
        'description', p.description, 'is_active', p.is_active
      ) order by p.id)
      from public.quero_products p
      join public.quero_categories c on c.id = p.category_id
    ), '[]'::jsonb),
    'surprise_boxes', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', b.id, 'name', b.name, 'description', b.description, 'price', b.price,
        'category_id', b.category_id, 'category', c.name,
        'min_price', b.min_price, 'max_price', b.max_price,
        'eligible_count', (
          select count(*)::integer
          from public.quero_products p
          join public.quero_categories pc on pc.id = p.category_id and pc.is_active
          where p.is_active
            and (b.category_id is null or p.category_id = b.category_id)
            and (b.min_price is null or coalesce(p.offer_price, p.price) >= b.min_price)
            and (b.max_price is null or coalesce(p.offer_price, p.price) <= b.max_price)
        ),
        'is_active', b.is_active
      ) order by b.id)
      from public.quero_surprise_boxes b
      left join public.quero_categories c on c.id = b.category_id
    ), '[]'::jsonb),
    'missions', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', id, 'icon', icon, 'title', title, 'detail', detail,
        'reward', reward, 'requirement', requirement, 'recurrence', recurrence,
        'is_active', is_active
      ) order by title)
      from public.quero_missions
    ), '[]'::jsonb),
    'settings', jsonb_build_object(
      'collection_reward', (select value from public.quero_admin_settings where key = 'collection_reward'),
      'demo_reward', (select value from public.quero_admin_settings where key = 'demo_reward'),
      'demo_cooldown_minutes', (select value from public.quero_admin_settings where key = 'demo_cooldown_minutes')
    ),
    'editors', case when v_is_admin then coalesce((
      select jsonb_agg(jsonb_build_object('email', u.email, 'created_at', a.created_at) order by u.email)
      from public.quero_admin_users a
      join auth.users u on u.id = a.user_id
      where a.role = 'editor'
    ), '[]'::jsonb) else '[]'::jsonb end
  );
end;
$function$;

create or replace function public.quero_admin_save_surprise_box(
  p_id integer, p_name text, p_description text, p_price integer,
  p_category_id text, p_min_price integer, p_max_price integer
)
returns integer
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_id integer;
begin
  if not public.quero_is_staff() then raise exception 'Administrator access required'; end if;
  if trim(coalesce(p_name, '')) = '' or length(p_name) > 100 then raise exception 'Invalid surprise box name'; end if;
  if length(coalesce(p_description, '')) > 500 then raise exception 'Surprise box description is too long'; end if;
  if p_price is null or p_price < 1 or p_price > 1000000 then raise exception 'Invalid surprise box price'; end if;
  if (p_min_price is null) <> (p_max_price is null)
    or (p_min_price is not null and (p_min_price < 1 or p_max_price < p_min_price or p_max_price > 1000000)) then
    raise exception 'Invalid surprise box price range';
  end if;
  if p_category_id is not null and not exists (
    select 1 from public.quero_categories where id = p_category_id and is_active
  ) then
    raise exception 'Active category not found';
  end if;

  if p_id is null then
    insert into public.quero_surprise_boxes (name, description, price, category_id, min_price, max_price)
    values (trim(p_name), trim(coalesce(p_description, '')), p_price, p_category_id, p_min_price, p_max_price)
    returning id into v_id;
  else
    update public.quero_surprise_boxes set
      name = trim(p_name), description = trim(coalesce(p_description, '')),
      price = p_price, category_id = p_category_id,
      min_price = p_min_price, max_price = p_max_price
    where id = p_id returning id into v_id;
    if not found then raise exception 'Surprise box not found'; end if;
  end if;
  return v_id;
end;
$function$;

create or replace function public.quero_admin_set_surprise_box_active(p_id integer, p_active boolean)
returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if not public.quero_is_staff() then raise exception 'Administrator access required'; end if;
  update public.quero_surprise_boxes set is_active = p_active where id = p_id;
  if not found then raise exception 'Surprise box not found'; end if;
  return true;
end;
$function$;

create or replace function public.quero_buy_surprise_box(p_box_id integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_state public.quero_user_state%rowtype;
  v_box public.quero_surprise_boxes%rowtype;
  v_product public.quero_products%rowtype;
  v_category_name text;
  v_owned integer[];
  v_new_rewards text[];
  v_reward integer := 0;
  v_collection_reward integer;
  v_refunded boolean;
  v_spent integer;
  v_balance integer;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;

  select * into v_state from public.quero_user_state
  where user_id = auth.uid() for update;
  if not found then raise exception 'Account state is not initialized'; end if;

  select * into v_box from public.quero_surprise_boxes
  where id = p_box_id and is_active for share;
  if not found then raise exception 'Surprise box not found'; end if;
  if v_state.balance < v_box.price then raise exception 'Insufficient virtual coins for surprise box'; end if;

  select p.* into v_product
  from public.quero_products p
  join public.quero_categories c on c.id = p.category_id and c.is_active
  where p.is_active
    and (v_box.category_id is null or p.category_id = v_box.category_id)
    and (v_box.min_price is null or coalesce(p.offer_price, p.price) >= v_box.min_price)
    and (v_box.max_price is null or coalesce(p.offer_price, p.price) <= v_box.max_price)
  order by random()
  limit 1;
  if not found then raise exception 'No products available for surprise box'; end if;

  v_refunded := v_product.id = any(v_state.owned_product_ids);
  v_spent := case when v_refunded then 0 else v_box.price end;
  v_balance := v_state.balance - v_spent;

  if not v_refunded then
    select array_agg(distinct product_id order by product_id)
    into v_owned
    from unnest(v_state.owned_product_ids || array[v_product.id]) as ids(product_id);

    select coalesce(array_agg(c.name order by c.name), '{}'::text[])
    into v_new_rewards
    from public.quero_categories c
    where c.is_active
      and exists (select 1 from public.quero_products p where p.category_id = c.id and p.is_active)
      and not (c.name = any(v_state.collection_rewards))
      and not exists (
        select 1 from public.quero_products p
        where p.category_id = c.id and p.is_active and not (p.id = any(v_owned))
      );
    select value into v_collection_reward from public.quero_admin_settings where key = 'collection_reward';
    v_reward := cardinality(v_new_rewards) * v_collection_reward;
    v_balance := v_balance + v_reward;
  else
    v_owned := v_state.owned_product_ids;
    v_new_rewards := '{}'::text[];
  end if;

  update public.quero_user_state
  set balance = v_balance,
      owned_product_ids = v_owned,
      collection_rewards = collection_rewards || v_new_rewards
  where user_id = auth.uid();

  select name into v_category_name from public.quero_categories where id = v_product.category_id;
  return jsonb_build_object(
    'refunded', v_refunded, 'spent', v_spent, 'reward', v_reward, 'balance', v_balance,
    'completed_categories', v_new_rewards,
    'product', jsonb_build_object(
      'id', v_product.id, 'name', v_product.name, 'category', v_category_name,
      'price', coalesce(v_product.offer_price, v_product.price),
      'original_price', case when v_product.offer_price is not null then v_product.price else null end,
      'emoji', v_product.emoji, 'color', v_product.color, 'tag', v_product.tag,
      'description', v_product.description
    )
  );
end;
$function$;

